export const LANGS = [
  { id: 'de', label: 'Deutsch' },
  { id: 'uk', label: 'Українська' },
];

let lang = 'de';

export function detectLang() {
  const l = (navigator.language || 'de').toLowerCase();
  return l.startsWith('uk') ? 'uk' : 'de';
}

export function setLang(l) {
  lang = STRINGS[l] ? l : 'de';
  document.documentElement.lang = lang;
}

export function getLang() {
  return lang;
}

export function tList(key) {
  const v = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.de[key];
  return Array.isArray(v) ? v : [];
}

export function t(key, vars) {
  let s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.de[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
  return s;
}

/** Plural forms: German Tag/Tage; Ukrainian день/дні/днів (also тиждень/тижні/тижнів). */
const PLURALS = {
  de: { day: ['Tag', 'Tage'], week: ['Woche', 'Wochen'] },
  uk: { day: ['день', 'дні', 'днів'], week: ['тиждень', 'тижні', 'тижнів'] },
};
export function plural(n, what) {
  const f = (PLURALS[lang] || PLURALS.de)[what];
  if (f.length === 2) return n === 1 ? f[0] : f[1];
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return f[0];
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return f[1];
  return f[2];
}
export const tDays = (n) => plural(n, 'day');

/**
 * Like t(), but returns [before, value, after] around one placeholder,
 * so the caller can render that value in bold.
 */
export function tSplit(key, vars, boldKey) {
  const rest = { ...vars };
  delete rest[boldKey];
  const s = t(key, rest);
  const marker = '{' + boldKey + '}';
  const i = s.indexOf(marker);
  if (i < 0) return [s, '', ''];
  return [s.slice(0, i), String(vars[boldKey]), s.slice(i + marker.length)];
}
